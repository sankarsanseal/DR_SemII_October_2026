CREATE TABLE IF NOT EXISTS MAJOR_STUDENT_COUNT(
  MAJOR_COURSE_CODE VARCHAR(20),
  MAJOR_COURSE_PAPER_NAME VARCHAR(100),
  MAJOR_NO_OF_YEARS VARCHAR(20),
  MAJOR_COLLEGE_CODE VARCHAR(10),
  MAJOR_COLLEGE_NAME VARCHAR(100),
  MAJOR_EXAM_CATEGORY VARCHAR(20),
  MAJOR_ROLL_COUNT INTEGER,
  PRIMARY KEY (
                MAJOR_COURSE_CODE, 
                MAJOR_COLLEGE_CODE, 
                MAJOR_NO_OF_YEARS, 
                MAJOR_EXAM_CATEGORY
  )
);


